"""
H507: latent_state_switching

Theory-first branch: test whether the C23-family behavior can be represented as
a small latent-state system (quiet, onset, amplification, carry) rather than a
collection of unrelated micro-conditioners.

This branch does not optimize portfolio construction. It maps structural state
organization, persistence, and transitions.
"""

